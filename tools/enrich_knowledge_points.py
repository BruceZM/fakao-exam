def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("input", type=Path)
    ap.add_argument("output", type=Path)
    args = ap.parse_args()
    doc = json.loads(args.input.read_text(encoding="utf-8"))
    for item in doc.get("items", []):
        searchable = " ".join([item.get("stem", ""), item.get("explanation", "")])
        subject = item.get("subject", "")
        tags = [name for name, pattern in TAGS.get(subject, []) if __import__("re").search(pattern, searchable)]
        manual = [p for p in item.get("knowledge_points", []) if p.get("source") == "manual_candidate"]
        merged = {p.get("name"): p for p in manual if p.get("name")}
        for tag in tags:
            merged.setdefault(tag, {"name": tag, "source": "auto_keyword", "review_status": "needs_human_review"})
        item["knowledge_points"] = list(merged.values())
        item["tagging_status"] = "auto_tagged" if tags else ("manual_candidate" if manual else "untagged")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tagged = sum(bool(x.get("knowledge_points")) for x in doc.get("items", []))
    print(f"items={len(doc.get('items', []))} tagged={tagged} output={args.output}")


if __name__ == "__main__":
    main()
